import re
from datetime import timedelta
from unittest.mock import patch
from django.conf import settings
from django.contrib.auth import get_user_model
from django.test import TestCase
from django.urls import reverse
from django.utils import timezone
from rest_framework.test import APIClient

from . import services
from .models import ShortURL
from .serializers import ShortURLSerializer

User = get_user_model()
AM_PM_REGEX = re.compile(r"^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2} (AM|PM)$")
BASE62_7CHAR_REGEX = re.compile(r"^[A-Za-z0-9]{7}$")


class TimezoneAndFormatTests(TestCase):
    def setUp(self):
        self.user = User.objects.create_user(email="test@example.com", password="S3cure-pass!")
        self.client = APIClient()
        self.client.force_authenticate(user=self.user)

    def test_settings_timezone_is_ist(self):
        self.assertEqual(settings.TIME_ZONE, "Asia/Kolkata")

    def test_short_url_serializer_formats_datetime_in_ist_am_pm(self):
        expires_at = timezone.now() + timedelta(days=2)
        short_url = ShortURL.objects.create(
            owner=self.user,
            short_code="test123",
            original_url="https://example.com",
            expires_at=expires_at,
        )
        serializer = ShortURLSerializer(short_url)
        data = serializer.data

        self.assertRegex(data["created_at"], AM_PM_REGEX)
        self.assertRegex(data["updated_at"], AM_PM_REGEX)
        self.assertRegex(data["expires_at"], AM_PM_REGEX)

    def test_create_short_url_with_am_pm_expires_at(self):
        url = reverse("shorturl-list")
        future_ist_str = (timezone.localtime(timezone.now()) + timedelta(days=2)).strftime("%Y-%m-%d %I:%M:%S %p")
        response = self.client.post(
            url,
            {"original_url": "https://example.com/target", "expires_at": future_ist_str},
            format="json",
        )
        self.assertEqual(response.status_code, 201)
        self.assertRegex(response.data["created_at"], AM_PM_REGEX)
        self.assertRegex(response.data["expires_at"], AM_PM_REGEX)

    def test_user_serializer_date_joined_format(self):
        url = reverse("me")
        response = self.client.get(url)
        self.assertEqual(response.status_code, 200)
        self.assertRegex(response.data["date_joined"], AM_PM_REGEX)


class ShortCodeAutogenerationTests(TestCase):
    def setUp(self):
        self.user = User.objects.create_user(email="user@example.com", password="S3cure-pass!")
        self.client = APIClient()
        self.client.force_authenticate(user=self.user)
        self.url = reverse("shorturl-list")

    def test_create_short_url_autogenerates_7char_code(self):
        response = self.client.post(
            self.url,
            {"original_url": "https://example.com/docs"},
            format="json",
        )
        self.assertEqual(response.status_code, 201)
        short_code = response.data["short_code"]
        self.assertEqual(len(short_code), 7)
        self.assertRegex(short_code, BASE62_7CHAR_REGEX)
        self.assertTrue(ShortURL.objects.filter(short_code=short_code).exists())

    def test_custom_alias_in_payload_is_ignored_and_autogenerated_7char_code_used(self):
        response = self.client.post(
            self.url,
            {"original_url": "https://example.com/page", "custom_alias": "mycustomlink"},
            format="json",
        )
        self.assertEqual(response.status_code, 201)
        short_code = response.data["short_code"]
        self.assertNotEqual(short_code, "mycustomlink")
        self.assertEqual(len(short_code), 7)
        self.assertRegex(short_code, BASE62_7CHAR_REGEX)
        self.assertFalse(ShortURL.objects.filter(short_code="mycustomlink").exists())

    def test_create_short_url_service_generates_7char_code(self):
        short_url = services.create_short_url(
            owner=self.user,
            original_url="https://example.com/service-test",
        )
        self.assertEqual(len(short_url.short_code), 7)
        self.assertRegex(short_url.short_code, BASE62_7CHAR_REGEX)

    def test_create_short_url_retries_on_reserved_and_duplicate_codes(self):
        existing = ShortURL.objects.create(
            owner=self.user,
            short_code="exist01",
            original_url="https://example.com/existing",
        )
        # Sequence: reserved code "admin", then existing code "exist01", then new code "brand01"
        with patch("shortener.services.generate_code", side_effect=["admin", "exist01", "brand01"]):
            created = services.create_short_url(
                owner=self.user,
                original_url="https://example.com/retry-test",
            )
        self.assertEqual(created.short_code, "brand01")

    def test_create_short_url_raises_code_generation_error_after_max_attempts(self):
        with patch("shortener.services.generate_code", return_value="admin"):
            with self.assertRaises(services.CodeGenerationError):
                services.create_short_url(
                    owner=self.user,
                    original_url="https://example.com/fail-test",
                )
